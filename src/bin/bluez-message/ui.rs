/// Link status dots (HFP calls, MAP messages, PBAP contacts), shared by the header and the wizard.
pub struct LinkDots {
    pub hfp: w::Link,
    pub map: w::Link,
    pub pbap: w::Link,
}

impl LinkDots {
    pub fn of(st: &State) -> Self {
        let hfp = match (st.hfp_up, st.slc) {
            (true, true) => w::Link::On,
            (true, false) => w::Link::Pending,
            _ => w::Link::Off,
        };
        let map = if st.map_up { w::Link::On } else { w::Link::Off };
        let pbap = match st.pbap {
            Some(true) => w::Link::On,
            Some(false) => w::Link::Pending,
            None => w::Link::Off,
        };
        Self { hfp, map, pbap }
    }
}

/// Language applied to the GUI texts.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Lang {
    /// No setting received from the daemon: system language.
    Unset,
    /// Daemon setting (`None`: system language).
    Set(Option<String>),
}

impl Lang {
    fn is(&self, code: Option<&str>) -> bool {
        matches!(self, Lang::Set(l) if l.as_deref() == code)
    }
}

pub struct App {
    /// `colors.plm` regenerated by matugen: colours reloaded hot.
    colors: theme::Watch,
    state: State,
    pal: Palette,
    /// Commands to the daemon; `None` after closing.
    tx: Option<UnboundedSender<Cmd>>,
    events: Receiver<Link>,
    target: Target,
    /// Left column: search and list.
    list: ConvList,
    /// Input of the message in the open thread.
    composer: Composer,
    /// Window in the foreground at the previous frame.
    was_focused: bool,
    /// Settings view open in place of the thread.
    prefs: Option<crate::prefs::View>,
    /// Setup wizard, in place of Settings and the thread.
    setup: Option<Wizard>,
    /// Device of the displayed data; another one in the settings resets the view.
    device: Option<BtAddr>,
    /// Language applied to the GUI; survives reconnections.
    lang: Lang,
    /// Colour emojis (Twemoji SVG).
    emojis: Emojis,
    /// Text size applied (zoom); `None`: no setting received.
    text_size: Option<TextSize>,
}

impl App {
    pub fn new(pal: Palette, tx: UnboundedSender<Cmd>, events: Receiver<Link>) -> Self {
        Self { colors: theme::Watch::new(), state: State::default(), pal, tx: Some(tx), events, target: Target::None, list: ConvList::default(), composer: Composer::default(), was_focused: false, prefs: None, setup: None, device: None, lang: Lang::Unset, emojis: Emojis::default(), text_size: None }
    }

    /// Local validation (immediate feedback), then sent to the daemon which revalidates.
    fn submit(&mut self, cmd: Cmd) -> bool {
        if let Cmd::Send { to, text } = &cmd
            && let Err(e) = validate_send(to, text)
        {
            self.state.error = Some(e);
            return false;
        }
        match &self.tx {
            Some(tx) if tx.send(cmd).is_ok() => true,
            _ => {
                self.state.error = Some(t!("connection to the daemon closed").into());
                false
            }
        }
    }

    fn on_link(&mut self, l: Link) {
        match l {
            // The daemon snapshot follows: start again from an empty state.
            Link::Up => self.state = State::default(),
            Link::Down(msg) => {
                // Conversations kept on screen; links and call reset.
                let mut st = State::default();
                st.convs = std::mem::take(&mut self.state.convs);
                // No more result to wait for: sends in progress turn into failures (resend possible).
                st.expire_pending(true);
                st.error = Some(msg);
                self.state = st;
            }
            // Notifications are the daemon's business: effects ignored.
            Link::Event(o) => {
                drop(self.state.apply(*o));
                self.follow_device();
                // Language changed by the daemon: GUI texts reloaded immediately.
                if let Some(p) = &self.state.settings
                    && !self.lang.is(p.settings.lang.as_deref())
                {
                    bluez_message::i18n::set_lang(p.settings.lang.as_deref());
                    self.lang = Lang::Set(p.settings.lang.clone());
                }
            }
        }
    }

    fn send_draft(&mut self) {
        let to = match &self.target {
            Target::Conv(k) => match self.state.conv(k) {
                Some(c) => c.number.clone(),
                None => return,
            },
            // Contact number ("+33 6 12…"): separators removed for sending.
            Target::Contact { number, .. } => bluez_message::phone::strip_separators(number),
            Target::None => return,
        };
        let text = self.composer.draft.trim().to_owned();
        if text.is_empty() {
            return;
        }
        if self.send(&to, &text) {
            self.composer.draft.clear();
            self.state.error = None;
        }
    }

    /// Send: the bubble appears at once, pending the transfer result.
    fn send(&mut self, to: &str, text: &str) -> bool {
        if !self.submit(Cmd::Send { to: to.to_owned(), text: text.to_owned() }) {
            return false;
        }
        self.state.pending(to, text);
        true
    }

    /// Header (`MenuHeader`); on the right, the link status dots (HFP call, MAP messages, PBAP contacts).
    fn header(&mut self, ui: &mut egui::Ui) {
        let pal = self.pal;
        let LinkDots { hfp, map, pbap } = LinkDots::of(&self.state);
        let rect = w::header(ui, &pal, Icon::Message, "MESSAGES");
        right_of(ui, rect.shrink2(egui::vec2(size::EDGE, 0.0)), |ui| {
            ui.spacing_mut().item_spacing.x = 16.0;
            w::status_dot(ui, &pal, Icon::Phone, hfp)
                .on_hover_text(t!("HFP (Hands-Free Profile): calls and call audio. Lit with a halo: ready; lit without a halo: connecting; dim: not connected."));
            w::status_dot(ui, &pal, Icon::MessageText, map)
                .on_hover_text(t!("MAP (Message Access Profile): reading and sending texts. Lit with a halo: connected; dim: not connected."));
            let pbap_tip = t!("PBAP (Phone Book Access Profile): contact names, synced every 6 hours. Lit with a halo: last sync succeeded; lit without a halo: last sync failed (allow Sync Contacts on the iPhone); dim: not synced yet.");
            w::status_dot(ui, &pal, Icon::Contacts, pbap).on_hover_text(pbap_tip);
        });
    }

    /// Device switched (daemon restarted on another one): open thread and list reset. Without a
    /// device, the wizard opens; it cannot be closed until one is configured.
    fn follow_device(&mut self) {
        let Some(p) = &self.state.settings else { return };
        if p.device.is_none() && self.setup.is_none() {
            self.prefs = None;
            self.setup = Some(Wizard::default());
        }
        if self.device != p.device {
            self.device.clone_from(&p.device);
            self.target = Target::None;
            self.list = ConvList::default();
            self.composer = Composer::default();
        }
    }

    /// Closes the wizard, unless no device is configured; `true` if it is closed.
    fn close_setup(&mut self) -> bool {
        if self.device.is_some()
            && let Some(s) = self.setup.take()
        {
            for c in s.leave(&self.state) {
                self.submit(c);
            }
        }
        self.setup.is_none()
    }

    /// No field keeps focus (arrows for the side view).
    fn release_focus(ctx: &egui::Context) {
        ctx.memory_mut(|m| {
            if let Some(id) = m.focused() {
                m.surrender_focus(id);
            }
        });
    }

    /// Settings or the wizard open in place of the thread.
    fn side_view(&self) -> bool {
        self.prefs.is_some() || self.setup.is_some()
    }

    /// Left column: conversations, and Settings at the bottom (rule then row).
    fn side(&mut self, ui: &mut egui::Ui) {
        let full = ui.max_rect();
        let foot_h = 1.0 + w::GAP * 2.0 + size::ROW_H;
        let (top, foot) = full.split_top_bottom_at_y(full.bottom() - foot_h);
        let pal = self.pal;
        let keys = !self.side_view();
        let acts = ui.scope_builder(egui::UiBuilder::new().max_rect(top), |ui| self.list.show(ui, &pal, &mut self.emojis, &self.state, &self.target, keys)).inner;
        for a in acts {
            match a {
                ListAction::Delete(key) => self.delete_conv(key),
                ListAction::Open(t) => self.open(t),
            }
        }
        let open = self.prefs.is_some();
        let clicked = ui
            .scope_builder(egui::UiBuilder::new().max_rect(foot), |ui| {
                w::rule(ui, &pal);
                ui.add_space(w::GAP * 2.0);
                let r = w::Row { icon: Some(Icon::Cog), label: t!("Settings"), sub: None, hint: "Ctrl+,", badge: 0, selected: open, strong: open };
                w::row(ui, &pal, &r).clicked()
            })
            .inner;
        if clicked {
            self.toggle_prefs(ui.ctx());
        }
    }

    /// Opens or closes Settings; when open, no field keeps focus (arrows for the view).
    fn toggle_prefs(&mut self, ctx: &egui::Context) {
        if !self.close_setup() {
            return;
        }
        if self.prefs.take().is_none() {
            self.prefs = Some(crate::prefs::View::default());
            Self::release_focus(ctx);
        } else {
            self.focus_target();
        }
    }

    /// Cursor in the search, or in the message if a thread is open.
    fn focus_target(&mut self) {
        let list = self.target == Target::None;
        (self.list.focus, self.composer.focus) = (list, !list);
    }

    /// Daemon information (reconnection, purge): text in `fg`, like the error banner.
    fn info_banner(&mut self, ui: &mut egui::Ui) {
        if let Some(m) = &self.state.info
            && w::banner(ui, &self.pal, Icon::Info, m, self.pal.fg)
        {
            self.state.info = None;
        }
    }

    /// Error (daemon stopped, link, send refused): text in danger, like `wifi_error`, and its cross.
    fn error_banner(&mut self, ui: &mut egui::Ui) {
        if let Some(e) = &self.state.error
            && w::banner(ui, &self.pal, Icon::Alert, e, self.pal.danger)
        {
            self.state.error = None;
        }
    }

    /// Call banner: call card, buttons 120 × 26 at 10 from the edge.
    fn call_banner(&mut self, ui: &mut egui::Ui) {
        let c = &self.state.call;
        let what = match c.phase {
            Phase::Incoming => t!("Incoming call"),
            Phase::Outgoing => t!("Outgoing call"),
            Phase::Active => t!("In call"),
            Phase::Idle => return,
        };
        let who = c.caller("  ·  ");
        let incoming = c.phase == Phase::Incoming;
        let pal = self.pal;
        let rect = w::call_card(ui, &pal, Icon::Phone, pal.accent, &who, what, pal.muted());
        let (mut answer, mut hangup) = (false, false);
        right_of(ui, rect.shrink2(egui::vec2(10.0, 0.0)), |ui| {
            hangup = w::button(ui, &pal, t!("HANG UP"), w::Tone::Danger).clicked();
            if incoming {
                answer = w::button(ui, &pal, t!("ANSWER"), w::Tone::Accent).clicked();
            }
        });
        if hangup {
            self.submit(Cmd::Hangup);
        }
        if answer {
            self.submit(Cmd::Answer);
        }
    }

    /// Deletes a conversation (locally then on the daemon side); if open, the thread empties.
    fn delete_conv(&mut self, key: String) {
        if matches!(&self.target, Target::Conv(k) if *k == key) {
            self.target = Target::None;
        }
        self.state.delete(&key, None);
        self.submit(Cmd::Delete { key, item: None });
    }

    /// Opens a target chosen from the list: closes Settings, focus on the input.
    fn open(&mut self, t: Target) {
        if !self.close_setup() {
            return;
        }
        self.prefs = None;
        self.list.opened(&t);
        self.composer.focus = true;
        self.target = t;
    }

    fn compose(&mut self, ui: &mut egui::Ui) {
        match self.composer.show(ui, &self.pal, &mut self.emojis) {
            Some(ComposerAction::Send) => self.send_draft(),
            Some(ComposerAction::Leave) => self.list.focus = true,
            None => {}
        }
    }

    fn thread(&mut self, ui: &mut egui::Ui) {
        let pal = self.pal;
        // Chosen contact whose conversation now exists (SMS sent, call logged): switch to it.
        if let Target::Contact { number, .. } = &self.target
            && self.state.conv(&self.state.key(number)).is_some()
        {
            self.target = Target::Conv(self.state.key(number));
        }
        let calls = self.list.tab == Tab::Calls;
        let key = match &self.target {
            Target::Conv(key) => key.clone(),
            Target::Contact { name, number } => {
                if thread::contact(ui, &pal, name, number, calls) {
                    let number = number.clone();
                    self.dial(&number);
                }
                return;
            }
            Target::None => return thread::placeholder(ui, &pal, t!("Select a conversation or search for a contact")),
        };
        // Read only if the window is in the foreground (otherwise the message was not seen).
        if ui.ctx().input(|i| i.focused) && let Some(until) = self.state.mark_read(&key, calls) {
            self.submit(Cmd::MarkRead { key: key.clone(), until });
        }
        let Some(c) = self.state.conv(&key) else {
            w::hint(ui, &pal, t!("Sending…"));
            return;
        };
        let acts = thread::conv(ui, &pal, &mut self.emojis, c, self.state.rev(), calls);
        let number = c.number.clone();
        self.apply(&key, &number, acts);
    }

    /// Actions requested from the bubbles of thread `key` (correspondent `number`).
    fn apply(&mut self, key: &str, number: &str, acts: Vec<ThreadAction>) {
        for a in acts {
            match a {
                ThreadAction::Resend(text) => drop(self.send(number, &text)),
                ThreadAction::React(emoji, text) => {
                    if let Some(t) = tapback::format(emoji, &text) {
                        self.send(number, &t);
                    }
                }
                ThreadAction::Delete(item) => {
                    self.state.delete(key, Some(&item));
                    if self.state.conv(key).is_none() {
                        self.target = Target::None;
                    }
                    self.submit(Cmd::Delete { key: key.to_owned(), item: Some(item) });
                }
                ThreadAction::Dial => self.dial(number),
            }
        }
    }

    /// Call from the iPhone: HFP ready and no call in progress; the popup opens on dialling.
    fn dial(&mut self, number: &str) {
        let err = if !(self.state.hfp_up && self.state.slc) {
            Some(t!("cannot call: phone not connected (HFP)").to_owned())
        } else if !self.state.call.is_idle() {
            Some(t!("cannot call: a call is already in progress").to_owned())
        } else {
            dial_number(number).err()
        };
        match err {
            Some(e) => self.state.error = Some(e),
            None => drop(self.submit(Cmd::Dial { number: number.to_owned() })),
        }
    }
}

impl eframe::App for App {
    fn logic(&mut self, ctx: &egui::Context, _frame: &mut eframe::Frame) {
        while let Ok(l) = self.events.try_recv() {
            self.on_link(l);
        }
        if self.state.expire_pending(false) {
            // Send bar animation.
            ctx.request_repaint_after(std::time::Duration::from_millis(33));
        }
        if let Some(p) = self.colors.poll(ctx) {
            self.pal = p;
        }
        // Zoom set on change only: egui's Ctrl+/- stays usable between two settings.
        if let Some(z) = self.state.settings.as_ref().map(|p| p.settings.text_size)
            && self.text_size != Some(z)
        {
            self.text_size = Some(z);
            ctx.set_zoom_factor(z.zoom());
        }
    }

    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        let pal = self.pal;
        // Back in the foreground: cursor in the search, or in the message if a thread is open.
        let focused = ui.ctx().input(|i| i.focused);
        if focused && !self.was_focused && !self.side_view() {
            self.focus_target();
        }
        self.was_focused = focused;
        if ui.input_mut(|i| i.consume_key(egui::Modifiers::COMMAND, Key::F)) && self.close_setup() {
            self.prefs = None;
            self.list.focus = true;
        }
        if ui.input_mut(|i| i.consume_key(egui::Modifiers::COMMAND, Key::Comma)) {
            self.toggle_prefs(ui.ctx());
        }
        let side = |l: i8, r: i8, t: i8, b: i8| Frame::new().fill(pal.bg).inner_margin(Margin { left: l, right: r, top: t, bottom: b });
        let p = w::PAD;
        Panel::top("head").frame(side(p, p, 2, 2)).show(ui, |ui| self.header(ui));
        if self.state.error.is_some() || self.state.info.is_some() || !self.state.call.is_idle() {
            Panel::top("alerts").show_separator_line(false).frame(side(p, p, w::TOP, 0)).show(ui, |ui| {
                ui.spacing_mut().item_spacing.y = w::GAP;
                self.call_banner(ui);
                self.error_banner(ui);
                self.info_banner(ui);
            });
        }
        Panel::left("convs").resizable(false).exact_size(340.0).frame(side(p, p, w::TOP, w::TOP)).show(ui, |ui| self.side(ui));
        // Calls tab: calling only, from the thread header.
        if self.target != Target::None && !self.side_view() && self.list.tab == Tab::Sms {
            Panel::bottom("compose").frame(side(p, p, w::TOP, w::TOP)).show(ui, |ui| self.compose(ui));
        }
        CentralPanel::default_margins().frame(side(p, p, 0, 4)).show(ui, |ui| {
            if let Some(s) = self.setup.as_mut() {
                let (cmds, close) = s.show(ui, &pal, &self.state);
                for c in cmds {
                    self.state.pairing.sent(&c);
                    self.submit(c);
                }
                if close && self.close_setup() {
                    self.focus_target();
                }
            } else if let Some(v) = self.prefs.as_mut() {
                let links = (self.state.map_up, self.state.hfp_up && self.state.slc, self.state.pbap == Some(true));
                let (cmds, nav) = v.show(ui, &pal, self.state.settings.as_ref(), links);
                for c in cmds {
                    self.submit(c);
                }
                match nav {
                    Nav::Stay => {}
                    Nav::Close => self.toggle_prefs(ui.ctx()),
                    Nav::Setup => {
                        (self.prefs, self.setup) = (None, Some(Wizard::default()));
                        Self::release_focus(ui.ctx());
                    }
                }
            } else {
                self.thread(ui);
            }
        });
    }

    fn on_exit(&mut self) {
        // Closes the connection; the daemon keeps running.
        self.tx = None;
    }
}
